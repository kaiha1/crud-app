import { test, expect } from '@playwright/test';
test('signup, task CRUD, filtering, persistent login, and logout', async ({ page }, testInfo) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const email = `test-${testInfo.project.name}-${Date.now()}@example.com`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Sign up', exact: true }).click();
  await page.getByLabel('Your name').fill('Alex Morgan'); await page.getByLabel('Email address').fill(email); await page.getByLabel('Password', { exact: true }).fill('correct-horse-123');
  await page.getByRole('button', { name: 'Create account' }).click();
  await expect(page.getByRole('heading', { name: 'A little progress, every day.' })).toBeVisible();
  await page.getByRole('button', { name: 'New task' }).click();
  await page.getByLabel('Task title').fill('Plan the next release'); await page.getByLabel('Description').fill('Review the checklist');
  await page.getByRole('button', { name: 'Create task', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Plan the next release' })).toBeVisible();
  await page.reload(); await expect(page.getByRole('heading', { name: 'Plan the next release' })).toBeVisible();
  await page.getByRole('button', { name: 'Edit Plan the next release', exact: true }).click();
  await page.getByLabel('Task title').fill('Ship the next release'); await page.getByLabel('Status', { exact: true }).selectOption('doing');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await page.getByRole('button', { name: 'Completed', exact: true }).click(); await expect(page.getByText('No tasks here yet.')).toBeVisible();
  await page.getByRole('button', { name: 'All tasks', exact: true }).click();
  await page.getByRole('searchbox', { name: 'Search tasks' }).fill('not a match'); await expect(page.getByText('No tasks here yet.')).toBeVisible();
  await page.getByRole('searchbox', { name: 'Search tasks' }).fill('');
  await page.getByRole('button', { name: 'Mark completed: Ship the next release', exact: true }).click();
  await expect(page.locator('.badge')).toHaveText('Completed');
  await page.screenshot({ path: `test-results/${testInfo.project.name}-workspace.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Delete Ship the next release', exact: true }).click();
  await page.getByRole('button', { name: 'Keep task' }).click(); await expect(page.getByRole('heading', { name: 'Ship the next release' })).toBeVisible();
  await page.getByRole('button', { name: 'Delete Ship the next release', exact: true }).click(); await page.getByRole('button', { name: 'Delete task', exact: true }).click();
  await expect(page.getByText('A fresh page. A clear mind.')).toBeVisible();
  await page.getByRole('button', { name: 'Log out' }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible();
  await page.locator('#login-tab').click();
  await page.getByLabel('Email address').fill(email); await page.getByLabel('Password', { exact: true }).fill('wrong-password');
  await page.getByRole('button', { name: 'Log in →', exact: true }).click(); await expect(page.getByRole('alert')).toHaveText('Incorrect email or password.');
  await page.getByLabel('Password', { exact: true }).fill('correct-horse-123'); await page.getByRole('button', { name: 'Log in →', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'A little progress, every day.' })).toBeVisible(); expect(errors).toEqual([]);
});
